# ---- 4. Optional negative-binomial convergence audit ------------------------
# Unlike the earlier sensitivity analysis, NB outputs are labeled UNRELIABLE
# when glm.nb reports iteration/alternation warnings; the script never silently
# presents a non-converged NB coefficient as confirmation.
fit_nb_safely <- function(formula, d) {
  warns <- character()
  res <- withCallingHandlers(
    tryCatch(MASS::glm.nb(formula, data = d,
                          control = stats::glm.control(maxit = 200)),
             error = function(e) e),
    warning = function(w) {
      warns <<- c(warns, conditionMessage(w))
      invokeRestart("muffleWarning")
    }
  )
  if (inherits(res, "error")) {
    return(list(ok = FALSE, model = NULL,
                status = paste("ERROR:", conditionMessage(res)), theta = NA_real_))
  }
  fail_pattern <- "alternation limit|iteration limit|did not converge|algorithm stopped"
  all_warnings <- unique(c(warns, if (!is.null(res$th.warn)) res$th.warn))
  good <- isTRUE(res$converged) && is.finite(res$theta) && res$theta > 0 &&
    !any(grepl(fail_pattern, all_warnings, ignore.case = TRUE)) &&
    all(is.finite(stats::coef(res)))
  list(ok = good, model = res,
       status = if (length(all_warnings)) paste(all_warnings, collapse = " | ")
                else if (good) "converged without warnings" else "not converged",
       theta = as.numeric(res$theta))
}

nb_cases <- list(
  all_two_harmonics = list(d = x, season = "two_harmonics"),
  all_month_fixed = list(d = x, season = "month_fixed"),
  all_one_harmonic = list(d = x, season = "one_harmonic"),
  later_two_harmonics = list(d = periods$later_2013_2019,
                             season = "two_harmonics")
)
nb_results <- list()
if (have_mass) {
  message("Checking negative-binomial convergence (supportive only)...")
  for (name in names(nb_cases)) {
    case <- nb_cases[[name]]
    fs <- make_formulas(case$season, "rsv_only")
    nb0 <- fit_nb_safely(fs$baseline, case$d)
    nb1 <- fit_nb_safely(fs$extended, case$d)
    trustworthy <- isTRUE(nb0$ok) && isTRUE(nb1$ok)
    effect <- if (trustworthy) {
      tryCatch(hac_effect(nb1$model, fs$rsv), error = function(e) NULL)
    } else NULL
    trustworthy <- trustworthy && !is.null(effect)
    nb_results[[length(nb_results) + 1L]] <- data.frame(
      model = name, n_months = nrow(case$d),
      baseline_status = nb0$status, full_status = nb1$status,
      baseline_theta = nb0$theta, full_theta = nb1$theta,
      usable = trustworthy,
      IRR = if (trustworthy) effect[["IRR"]] else NA_real_,
      CI_low = if (trustworthy) effect[["CI_low"]] else NA_real_,
      CI_high = if (trustworthy) effect[["CI_high"]] else NA_real_,
      p_HAC = if (trustworthy) effect[["p_HAC"]] else NA_real_,
      delta_AIC = if (trustworthy)
        stats::AIC(nb1$model) - stats::AIC(nb0$model) else NA_real_,
      stringsAsFactors = FALSE)
  }
  nb_results <- do.call(rbind, nb_results)
} else {
  nb_results <- data.frame(model = "not_run", n_months = NA_integer_,
     baseline_status = "MASS package not installed", full_status = NA_character_,
     baseline_theta = NA_real_, full_theta = NA_real_, usable = FALSE,
     IRR = NA_real_, CI_low = NA_real_, CI_high = NA_real_,
     p_HAC = NA_real_, delta_AIC = NA_real_)
}
