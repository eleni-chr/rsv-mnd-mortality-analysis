# Final technical validation: RSV circulation and motor neuron disease mortality
# US CDC WONDER underlying-cause G12.2 deaths, monthly January 2011-Dec 2019.
#
# RUN FROM PROJECT DIRECTORY:
#   source("03_RSV_technical_validation.R")
#
# This is a separate follow-up to the original pilot/sensitivity scripts.
# Input: sensitivity_analysis_dataset.csv generated by script 02 in sensitivity_results/.
# If supplied separately, place the file in input_data/.
#
# Questions fixed BEFORE inspecting these new model estimates:
#   1. Is PCR-only RSV associated with mortality in a Poisson model with
#      Newey-West/HAC standard errors (rather than potentially non-converged NB)?
#   2. Is the effect similar under two Fourier harmonics, calendar-month effects,
#      and a less flexible one-harmonic seasonal adjustment? (Same trend df.)
#   3. Is the effect reasonably consistent during 2013-2019, without 2011-12?
#   4. Is the result dependent on influenza adjustment, CDC-flagged RSV outliers,
#      or a step indicator corresponding to the original 2015 lab-era change?
#   5. Is a negative-binomial model reliable enough to serve as a corroboration?
#
# Exposure throughout: mean RSV PCR test positivity in current + previous month,
#                   scaled to +5 percentage points.
# No lag selection or p-value optimisation is performed in this script.
# Models are ecological associations, not causal or individual risk estimates.
# =============================================================================

