# ---- 1. Model specifications -------------------------------------------------
# Keep 4 df secular trend in ALL three seasonal comparisons to avoid changing
# trend flexibility and seasonal flexibility at the same time.
season_term <- function(season) {
  switch(season,
    two_harmonics = "sin1 + cos1 + sin2 + cos2",
    month_fixed   = "month_factor",
    one_harmonic  = "sin1 + cos1",
    stop("Unexpected seasonal specification: ", season))
}

rsv_term <- function(variant) {
  switch(variant,
    pcr = "rsv_pcr_mean01_5pp",
    pcr_excluding_outliers = "rsv_pcr_no_outliers_mean01_5pp",
    stop("Unexpected RSV variant: ", variant))
}

make_formulas <- function(season, exposure, variant = "pcr", lab_era = TRUE) {
  baseline <- paste("splines::ns(t, df = 4)", season_term(season), sep = " + ")
  if (lab_era) baseline <- paste(baseline, "flu_lab_era", sep = " + ")
  baseline <- paste(baseline, "offset(log(days))", sep = " + ")
  predictor <- rsv_term(variant)
  if (exposure == "joint") predictor <- paste(predictor, "flu_mean01_5pp", sep = " + ")
  if (!exposure %in% c("rsv_only", "joint")) stop("Unknown exposure type")
  list(
    baseline = stats::as.formula(paste("deaths ~", baseline)),
    extended = stats::as.formula(paste("deaths ~", baseline, "+", predictor)),
    rsv = rsv_term(variant), flu = if (exposure == "joint") "flu_mean01_5pp" else NULL
  )
}

# ---- 2. Fitting functions -----------------------------------------------------
hac_effect <- function(model, predictor) {
  b <- stats::coef(model)
  if (!(predictor %in% names(b)) || !is.finite(b[[predictor]])) {
    stop("Coefficient missing or aliased: ", predictor)
  }
  V <- sandwich::NeweyWest(model, lag = 3, prewhite = FALSE, adjust = TRUE)
  v <- unname(V[predictor, predictor])
  if (!is.finite(v) || v <= 0) stop("Invalid HAC variance for ", predictor)
  se <- sqrt(v)
  z <- unname(b[[predictor]]) / se
  c(coefficient = unname(b[[predictor]]), HAC_SE = se,
    IRR = exp(unname(b[[predictor]])),
    CI_low = exp(unname(b[[predictor]]) - 1.96 * se),
    CI_high = exp(unname(b[[predictor]]) + 1.96 * se),
    p_HAC = 2 * stats::pnorm(-abs(z)))
}

fit_poisson <- function(formula, d) {
  # No negative-binomial dispersion iteration; Poisson mean coefficients
  # accompanied by autocorrelation/heteroskedasticity-robust HAC inference.
  mod <- stats::glm(formula, data = d, family = stats::poisson(link = "log"),
                    control = stats::glm.control(maxit = 100))
  if (!isTRUE(mod$converged) || any(!is.finite(stats::coef(mod)))) {
    stop("Poisson fit did not converge / yielded non-finite coefficients")
  }
  mod
}

pearson_dispersion <- function(model) {
  sum(stats::residuals(model, type = "pearson")^2) / stats::df.residual(model)
}

lb_p <- function(model) {
  stats::Box.test(stats::residuals(model, type = "pearson"),
                  lag = 12, type = "Ljung-Box")$p.value
}

fit_check <- function(label, d, season = "two_harmonics", exposure = "rsv_only",
                      variant = "pcr", lab_era = TRUE) {
  f <- make_formulas(season, exposure, variant, lab_era)
  null <- fit_poisson(f$baseline, d)
  full <- fit_poisson(f$extended, d)
  e <- hac_effect(full, f$rsv)
  flu <- if (!is.null(f$flu)) hac_effect(full, f$flu) else NULL
  data.frame(
    specification = label,
    period = paste0(min(d$year), "-", max(d$year)),
    omitted_year = if (all(2011:2019 %in% d$year)) NA_integer_
                   else if (length(setdiff(2011:2019, unique(d$year))) == 1L)
                     setdiff(2011:2019, unique(d$year)) else NA_integer_,
    months = nrow(d), seasonality = season, exposure = exposure,
    RSV_measure = variant, lab_era_adjustment = lab_era,
    beta = e[["coefficient"]], HAC_SE = e[["HAC_SE"]],
    IRR = e[["IRR"]], CI_low = e[["CI_low"]],
    CI_high = e[["CI_high"]], p_HAC = e[["p_HAC"]],
    flu_IRR = if (is.null(flu)) NA_real_ else flu[["IRR"]],
    flu_p_HAC = if (is.null(flu)) NA_real_ else flu[["p_HAC"]],
    baseline_AIC = stats::AIC(null), extended_AIC = stats::AIC(full),
    delta_AIC = stats::AIC(full) - stats::AIC(null),
    baseline_dispersion = pearson_dispersion(null),
    full_dispersion = pearson_dispersion(full),
    baseline_LjungBox_p12 = lb_p(null),
    full_LjungBox_p12 = lb_p(full),
    stringsAsFactors = FALSE
  )
}

