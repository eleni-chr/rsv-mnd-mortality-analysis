add <- function(label, d, season = "two_harmonics", exposure = "rsv_only",
                variant = "pcr", lab_era = TRUE) {
  results[[length(results) + 1L]] <<- fit_check(
    label, d, season = season, exposure = exposure,
    variant = variant, lab_era = lab_era)
}
